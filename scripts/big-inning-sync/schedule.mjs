export const MLB_URL = "https://support.mlb.com/s/article/What-Is-MLB-Big-Inning?language=en_US";

function isoDate(value) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value ?? "")) return null;
  const date = new Date(`${value}T00:00:00Z`);
  return Number.isFinite(date.getTime()) && date.toISOString().slice(0, 10) === value ? value : null;
}

export function tupleDate(value) {
  const match = /^(\d{1,2})\/(\d{1,2})\/(\d{2}|\d{4})$/.exec(value ?? "");
  if (!match) return null;
  const year = match[3].length === 2 ? `20${match[3]}` : match[3];
  return isoDate(`${year}-${match[1].padStart(2, "0")}-${match[2].padStart(2, "0")}`);
}

function validTuple(tuple) {
  return Array.isArray(tuple) && tuple.length === 3 && tupleDate(tuple[0]) !== null
    && tuple.slice(1).every(value => /^(?:[1-9]|1[0-2]):[0-5]\d\s*(?:AM|PM)$/i.test(value));
}

export function tuplesFromRows(rows) {
  const tuples = rows.map(cells => cells.slice(1, 4)).filter(validTuple);
  return [...new Map(tuples.map(tuple => [tuple.join("|"), tuple])).values()];
}

export function savedTuples(source) {
  const body = /BIG_INNING_RAW[^=]*=\s*\[([\s\S]*?)\];/.exec(source)?.[1];
  if (!body) return [];
  try {
    const tuples = JSON.parse(`[${body.replace(/,\s*$/, "")}]`);
    return tuples.length && tuples.every(validTuple) ? tuples : [];
  } catch {
    return [];
  }
}

export function seasonDates(payload, year) {
  const season = payload?.seasons?.find(row => row.seasonId === String(year));
  const start = isoDate(season?.regularSeasonStartDate);
  const end = isoDate(season?.regularSeasonEndDate);
  if (!start || !end || start >= end || !start.startsWith(`${year}-`) || !end.startsWith(`${year}-`)) {
    throw new Error(`MLB did not return valid regular-season dates for ${year}`);
  }
  return { year, start, end };
}

export function easternDate(now = new Date()) {
  return new Intl.DateTimeFormat("en-CA", {
    timeZone: "America/New_York", year: "numeric", month: "2-digit", day: "2-digit",
  }).format(now);
}

// A missing article is expected only outside MLB's verified regular season,
// with a retained, valid schedule reaching the last completed season's finale.
// Empty rendering, permission errors, missing season metadata and in-season
// failures remain failures. No dates or windows are inferred from this check.
export function expectedNoSchedule({ source, tuples, today, currentSeason, previousSeason }) {
  if (source.kind !== "not-found" || ![200, 404].includes(source.httpStatus)
    || !isoDate(today) || !tuples.length || !tuples.every(validTuple)) return null;
  let completedSeason;
  if (today > currentSeason.end) completedSeason = currentSeason;
  else if (today < currentSeason.start) completedSeason = previousSeason;
  if (!completedSeason) return null;
  const dates = tuples.map(tuple => tupleDate(tuple[0])).sort();
  if (dates.at(-1) !== completedSeason.end || dates.some(date => !date.startsWith(`${completedSeason.year}-`))) return null;
  return { outcome: "no-published-schedule", completedSeason, nextSeasonStart: today < currentSeason.start ? currentSeason.start : null };
}

export function emitTs(tuples, generatedAt) {
  if (!tuples.length || !tuples.every(validTuple)) throw new Error("Refusing to publish an empty or invalid schedule");
  return `// Auto-generated by ~/scripts/big-inning-sync/sync.mjs on the Mac Mini.
// Source: ${MLB_URL}
// Manual edits are fine; the next sync will overwrite if it succeeds.

export const BIG_INNING_GENERATED_AT = ${JSON.stringify(generatedAt)};

export const BIG_INNING_RAW: ReadonlyArray<readonly [string, string, string]> = [
${tuples.map(tuple => `  ${JSON.stringify(tuple).replaceAll(",", ", ")},`).join("\n")}
];
`;
}

export const stripStamp = source => source.replace(/BIG_INNING_GENERATED_AT = "[^"]+"/, 'BIG_INNING_GENERATED_AT = ""');
